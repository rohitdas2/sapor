// Generates supabase/seed.sql from src/data/catalog.json (the same data the local demo uses).
// Usage: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const catalog = JSON.parse(readFileSync(new URL("../src/data/catalog.json", import.meta.url)));
const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const r = catalog.retailer;

const rows = catalog.products.map(
  (p) => `  (${q(r.id)}, ${q(p.name)}, ${q(p.slug)}, ${q(p.category)}, ${q(p.description)}, ${q(p.availability)}::availability_status)`,
);

const sql = `-- GENERATED by scripts/generate-seed.mjs from src/data/catalog.json. Do not edit by hand.
-- Catalog only. No users, reviews, ratings or activity are seeded.
insert into public.retailers (id, name, slug) values (${q(r.id)}, ${q(r.name)}, ${q(r.slug)})
on conflict (id) do nothing;

insert into public.products (retailer_id, name, slug, category, description, availability) values
${rows.join(",\n")}
on conflict (retailer_id, slug) do update set
  name = excluded.name, description = excluded.description,
  category = excluded.category, availability = excluded.availability;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${catalog.products.length} products to supabase/seed.sql`);
